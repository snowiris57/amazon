    let bestScore = 0;
    for (const cat of CATEGORIES) {
      if (!cat.keywords.length) continue;
      let score = 0;
      for (const kw of cat.keywords) {
        if (text.includes(normalize(kw))) {
          // 長いキーワードほど信頼度が高いので重み付け
          score += Math.min(kw.length, 6);
        }
      }
      if (score > bestScore) {
        bestScore = score;
        best = cat.id;
      }
    }
